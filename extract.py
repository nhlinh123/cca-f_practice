"""Extract questions from the saved practice-cert offline batches into questions.js.

Usage: python3 extract.py ccar-f-batch1.html [ccar-f-batch2.html ...] questions.js
"""
import re, sys, json, html
from html.parser import HTMLParser

*SRCS, OUT = sys.argv[1:]
ALLOWED = {'p', 'code', 'strong', 'em', 'ul', 'ol', 'li', 'h4', 'a', 'br', 'pre', 'blockquote'}


class Clean(HTMLParser):
    """Keep only an allowlist of tags; drop all attributes except https hrefs."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []

    def handle_starttag(self, tag, attrs):
        if tag not in ALLOWED:
            return
        if tag == 'a':
            href = dict(attrs).get('href', '')
            if not href.startswith('https://'):
                return
            self.out.append(f'<a href="{html.escape(href)}" target="_blank" rel="noopener">')
        else:
            self.out.append(f'<{tag}>')

    def handle_endtag(self, tag):
        if tag in ALLOWED and tag != 'br':
            self.out.append(f'</{tag}>')

    def handle_data(self, data):
        self.out.append(html.escape(data.replace('\\"', '"'), quote=False))


def clean(s):
    c = Clean()
    c.feed(s)
    out = re.sub(r'\s+', ' ', ''.join(c.out)).strip()
    return re.sub(r'`([^`<]+)`', r'<code>\1</code>', out)


def text(s):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', s))).strip()


def unwrap_p(s):
    m = re.fullmatch(r'<p>(.*)</p>', s, re.S)
    return m.group(1) if m and '<p>' not in m.group(1) else s


blocks = [b for src in SRCS
          for b in re.findall(r'<details class="qblock">.*?</details>', open(src, encoding='utf-8').read(), re.S)]
qs, notes = {}, []
for b in blocks:
    qid = re.search(r'data-question-id="(\d+)"', b).group(1)
    q = re.sub(r'<span class="qnum">.*?</span>', '', re.search(r'<summary>(.*?)</summary>', b, re.S).group(1))
    opts = sorted(re.findall(r'<label for="answer-\d+-([A-Z])".*?<div class="practice-option-content">(.*?)</div>', b, re.S))
    letters = [L for L, _ in opts]
    key = re.search(r'data-correct-option="([A-Z])"', b).group(1)  # every question is single-answer
    expl = re.search(r'<div class="practice-explanation-content">(.*?)</div>\s*</section>', b, re.S).group(1)
    # The site key is wrong on at least one question; when the explanation states its answer letter, trust it.
    m = re.search(r'3\. Đáp án</h4>\s*(?:<ul>\s*<li>)?\s*(?:<p>|<strong>)?\s*([A-D])\.', expl)
    if m and m.group(1) != key:
        notes.append(f'id {qid}: site key {key} -> explanation says {m.group(1)}')
        key = m.group(1)
    expl = clean(expl)
    # Explanations cite options by original letter ("<p>C. ", "<strong>C.", "(C)"); mark them so the app can relabel after shuffling.
    expl = re.sub(r'(<p>|<strong>)([A-D])\.', r'\1{{\2}}.', expl)
    expl = re.sub(r'\(([A-D])\)', r'({{\1}})', expl)
    qs[qid] = {
        'q': unwrap_p(clean(q)),
        'options': [unwrap_p(clean(o)) for _, o in opts],  # original A, B, C, D order
        'answer': letters.index(key),
        'explanation': expl,
    }

print(len(blocks), 'blocks ->', len(qs), 'questions')
print('\n'.join(notes))
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by extract.py. answer = index of the correct option; {{X}} in explanation = original option letter X.\n')
    f.write('window.QUESTIONS = ' + json.dumps(list(qs.values()), ensure_ascii=False, indent=1) + ';\n')
